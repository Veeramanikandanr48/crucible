import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { applyCameraOverride, applyCameraOverrideToDirectory, loadCameraOverrides } from '../bench/scene-frames/camera-overrides.mjs';

const FLAT_CAMERA = { id: 'monk', glb: 'scene.glb', eye: [0, 1, 0], target: [0, 1, 1], frame: { fov: 50 } };

test('the committed overrides give Lone Monk the courtyard camera and Barbershop a camera of its own', () => {
  const overrides = loadCameraOverrides();
  assert.deepEqual(overrides.monk.eye, [14, 1.6, -14]);
  assert.deepEqual(overrides.monk.target, [20, 1.8, -19.5]);
  assert.equal(overrides.barbershop.eye.length, 3);
  assert.equal(overrides.barbershop.target.length, 3);
});

test('an override replaces eye and target and keeps every other field', () => {
  const updated = applyCameraOverride('monk', FLAT_CAMERA, { monk: { eye: [14, 1.6, -14], target: [20, 1.8, -19.5] } });
  assert.deepEqual(updated.eye, [14, 1.6, -14]);
  assert.deepEqual(updated.target, [20, 1.8, -19.5]);
  assert.equal(updated.glb, 'scene.glb');
  assert.deepEqual(updated.frame, { fov: 50 });
});

test('a scene with no override is returned as it is', () => {
  assert.equal(applyCameraOverride('classroom', FLAT_CAMERA, { monk: { eye: [1, 1, 1], target: [2, 2, 2] } }), FLAT_CAMERA);
});

test('a malformed override throws an error that names the scene and the field', () => {
  assert.throws(() => applyCameraOverride('monk', FLAT_CAMERA, { monk: { eye: [1, 2], target: [0, 0, 0] } }), /"monk" needs eye as three finite numbers/);
});

test('a generated scene directory gets the committed camera written into scene.json', () => {
  const directory = mkdtempSync(join(tmpdir(), 'camera-override-'));
  try {
    writeFileSync(join(directory, 'scene.json'), JSON.stringify(FLAT_CAMERA));
    assert.equal(applyCameraOverrideToDirectory(directory, loadCameraOverrides()), true);
    const written = JSON.parse(readFileSync(join(directory, 'scene.json'), 'utf8'));
    assert.deepEqual(written.eye, loadCameraOverrides().monk.eye);
    assert.equal(applyCameraOverrideToDirectory(directory, {}), false);
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
});

test('a directory without scene.json says what to pass instead', () => {
  assert.throws(() => applyCameraOverrideToDirectory(join(tmpdir(), 'no-such-scene-directory'), {}), /generated by scripts\/blender-demo-to-glb\.py/);
});
